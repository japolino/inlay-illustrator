describe("AM label translation", () => {
  test("no Korean remains in any known controller text", () => {
    const left = SAMPLES.map((s) => [s, translateAmText(s)]).filter(([, t]) => /[\uac00-\ud7a3]/u.test(t!));
    expect(left).toEqual([]);
  });
  test("examples", () => {
    expect(translateAmText("프롬프트 분석 완료 · 2개 캐릭터 · 정보 없음 1개")).toBe("Prompt analysis complete · 2 characters · no info 1");
    expect(translateAmText("이미지 프롬프트 AI 분석 배치 1/3")).toBe("Image prompt AI analysis batch 1/3");
    expect(translateAmText("메타데이터 AI 배치 2: boom")).toBe("Metadata AI batch 2: boom");
    expect(amLabel("Ready")).toEqual({ label: "Ready" });
    expect(amLabel("프롬프트 분석 실패")).toEqual({ label: "Prompt analysis failed", labelKo: "프롬프트 분석 실패" });
  });
});
