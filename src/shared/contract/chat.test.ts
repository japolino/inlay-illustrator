describe("chat data document", () => {
  const NOW = "2026-01-01T00:00:00.000Z";
  const storeCase = (storeJson as Array<{ name: string; output: unknown }>).find((c) => c.name === "valid-mixed")!;
  const validDoc = (): ChatDataDocument => {
    const store = clone(storeCase.output) as ChatDataDocument["store"];
    const history = projectStoreToTree(store, "chat:lumi-chat-1");
    return { ...createEmptyChatData("lumi-chat-1", NOW), store: foldTreeIntoStore(store, history), history };
  };
  test("empty document", () => {
    const d = createEmptyChatData("lumi-chat-1", NOW);
    expect(d).toEqual({
      schema: CHAT_DATA_SCHEMA, version: 1, chatId: "lumi-chat-1", updatedAt: NOW, store: { messages: {} },
      history: createEmptyHistoryTree("chat:lumi-chat-1"), plans: {}, actorState: { revision: 0, actors: {} },
    });
    expect(validateChatData(d, "lumi-chat-1")).toEqual({ ok: true, data: d });
  });
  test("valid document round trip", () => {
    const d = validDoc();
    const plan = createIllustrationPlan({ messageId: "msg-2@1", messageIndex: 5 }, 3, 1);
    d.plans[plan.key] = plan;
    const r = validateChatData(clone(d), "lumi-chat-1");
    expect(r.ok).toBe(true);
    const n = normalizeChatData(clone(d), "lumi-chat-1", NOW);
    expect(n.repaired).toBe(false);
    expect(n.data).toEqual(d);
  });
  test("missing document -> empty, not repaired", () => {
    expect(normalizeChatData(undefined, "c", NOW)).toEqual({ data: createEmptyChatData("c", NOW), issues: [], repaired: false });
  });
  test("foreign document is reset", () => {
    const n = normalizeChatData({ messages: {} }, "c", NOW);
    expect(n.repaired).toBe(true);
    expect(n.data).toEqual(createEmptyChatData("c", NOW));
  });
  test("invalid history with valid store is rebuilt from the store", () => {
    const d = validDoc() as unknown as Record<string, unknown>;
    d.history = { chatKey: "chat:lumi-chat-1", entriesById: [], slotsById: {}, messagesByKey: {} };
    const n = normalizeChatData(d, "lumi-chat-1", NOW);
    expect(n.issues.map((i) => i.code)).toEqual(["entries-record", "history-rebuilt"]);
    expect(n.data.history).toEqual(validDoc().history);
    expect(listHistoryTreeIssues(n.data.history)).toEqual([]);
  });
  test("history of another chat is rejected", () => {
    const d = validDoc();
    const r = validateChatData({ ...d, history: { ...d.history, chatKey: "chat:other" } }, "lumi-chat-1");
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.issues.map((i) => i.code)).toEqual(["chat-key"]);
  });
  test("invalid store and actor state are reset and reported", () => {
    const d = validDoc() as unknown as Record<string, unknown>;
    d.store = { messages: { "id:1": { kind: "inline", generations: [] } } };
    d.actorState = { revision: -1, actors: {} };
    d.plans = { "illustration:x@0": { key: "illustration:y@0", messageId: "y@0" } };
    const n = normalizeChatData(d, "lumi-chat-1", NOW);
    expect(n.repaired).toBe(true);
    expect(n.data.store).toEqual({ messages: {} });
    expect(n.data.actorState).toEqual({ revision: 0, actors: {} });
    expect(n.data.plans).toEqual({});
    expect(n.data.history).toEqual(validDoc().history); // the history itself stays valid
    expect(n.issues.map((i) => `${i.part}:${i.code}`)).toEqual(["store:message-key", "plans:plan-invalid", "actorState:revision"]);
  });
  test("message ids without a swipe suffix are rejected", () => {
    const d = validDoc();
    d.store = { messages: { plain: { kind: "inline", generations: [] } } };
    const r = validateChatData(d, "lumi-chat-1");
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.issues.map((i) => i.code)).toContain("message-id-swipe");
  });
  test("strict validation reports document fields", () => {
    const r = validateChatData({ ...createEmptyChatData("c", NOW), version: 2, updatedAt: "x", extra: 1 }, "c");
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.issues.map((i) => i.code)).toEqual(["version", "updated-at", "unexpected-field"]);
  });
});
