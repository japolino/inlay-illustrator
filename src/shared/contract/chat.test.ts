describe("chat store validator parity (uN)", () => {
  const cases = storeJson as Array<{ name: string; input: unknown; output: unknown }>;
  for (const c of cases)
    test(c.name, () => {
      const r = validateChatStore(clone(c.input));
      expect(r.ok).toBe(c.output !== null);
      if (r.ok) expect(JSON.stringify(r.store)).toBe(JSON.stringify(c.output));
      else expect(r.issues.length).toBeGreaterThan(0);
    });
  test("Asset Maid localLore carrier content", () => {
    const store = (cases.find((c) => c.name === "valid-mixed")!.output) as object;
    expect(parseAssetMaidChatStoreContent(`@@dont_activate ${JSON.stringify(store)}`)).toEqual(store as never);
    expect(parseAssetMaidChatStoreContent("@@dont_activate {")).toBeNull();
    expect(parseAssetMaidChatStoreContent(`{"messages":{}}`)).toBeNull();
    expect(parseAssetMaidChatStoreContent(`@@dont_activate {"x":1}`)).toBeNull();
  });
  test("continuity canonicalizer (Xk) drops meta keys and zero counters", () => {
    expect(canonicalizeContinuity({ scene: { capturedAt: 1, place: "x" }, characters: { a: { cum_count: 0, description: "" } }, other: 1 })).toEqual({
      scene: { place: "x" },
    });
    expect(canonicalizeContinuity({})).toBeUndefined();
  });
});

describe("count policy parity (qf / Gf / IW / SW / w5)", () => {
  const cases = countJson as Array<{ input: unknown; qf: unknown; Gf: unknown; Gf3: unknown; IW: unknown; w5: unknown; SW: unknown[] }>;
  const decode = (v: unknown): unknown => (v === "__undefined__" ? undefined : v === "__nan__" ? Number.NaN : v);
  for (const c of cases)
    test(JSON.stringify(c.input), () => {
      const v = decode(c.input);
      expect(fixedCountPolicy(v)).toEqual(c.qf as never);
      expect(normalizeCountPolicy(v)).toEqual(c.Gf as never);
      expect(normalizeCountPolicy(v, 3)).toEqual(c.Gf3 as never);
      expect(countPolicyValues(v)).toEqual(c.IW as never);
      expect(normalizeRequestedCount(v)).toBe(c.w5 as number);
      expect([0, 1, 2, 4, 10].map((n) => clampCountPolicyToResolved(v, n))).toEqual(c.SW as never);
    });
  test("constants", () => {
    expect(MAX_IMAGE_COUNT).toBe(7);
    expect(UNLIMITED_IMAGE_COUNT).toBe(Number.MAX_SAFE_INTEGER);
    expect(fixedCountPolicy(1)).toEqual({ mode: "fixed", min: 1, max: 1, values: { fixed: 1, min: 1, max: 2 } });
  });
});

