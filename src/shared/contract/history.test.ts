type Json = unknown;
type Ref = { value?: Json; base?: string; patch?: Array<[Array<string | number>, Json?]> };
const BASES = basesJson as Record<string, Json>;
const clone = <T>(x: T): T => JSON.parse(JSON.stringify(x)) as T;

function resolve(ref: Ref, ctx: { input?: Json; previous?: Json } = {}): any {
  if ("value" in ref) return clone(ref.value);
  const base = ref.base === "$input" ? ctx.input : ref.base === "$previous" ? ctx.previous : BASES[ref.base as string];
  let out: any = clone(base);
  for (const op of ref.patch ?? []) {
    const path = op[0];
    if (!path.length) {
      out = clone(op[1]);
      continue;
    }
    let parent: any = out;
    for (const k of path.slice(0, -1)) parent = parent[k];
    const last = path[path.length - 1] as string;
    if (op.length === 1) delete parent[last];
    else parent[last] = clone(op[1]);
  }
  return out;
}

function errorMatches(fn: () => unknown, expected: string): void {
  let caught: unknown;
  try {
    fn();
  } catch (e) {
    caught = e;
  }
  expect(caught).toBeInstanceOf(Error);
  const e = caught as HistoryCommandError;
  const texts = [e.message, e.originalMessage];
  if (caught instanceof HistoryInvariantError) {
    // Asset Maid's invariant message is `${path}: ${korean}` per line.
    texts.push(caught.issues.map((i) => `${i.path}: ${i.messageKo}`).join("\n"));
  }
  expect(texts).toContain(expected);
}

