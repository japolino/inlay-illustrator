describe("projection parity (NR / lK)", () => {
  const p = projectJson as Array<{ name: string; store: ChatStore; chatKey: string; indexes: Record<string, number>; tree?: HistoryTree; error?: string }>;
  for (const c of p)
    test(`project ${c.name}`, () => {
      if (c.error !== undefined) return errorMatches(() => projectStoreToTree(clone(c.store), c.chatKey, c.indexes), c.error);
      expect(JSON.stringify(projectStoreToTree(clone(c.store), c.chatKey, new Map(Object.entries(c.indexes))))).toBe(JSON.stringify(c.tree));
    });
  const f = foldJson as Array<{ name: string; store: ChatStore; tree: Ref; result?: ChatStore; error?: string }>;
  for (const c of f)
    test(`fold ${c.name}`, () => {
      const tree = resolve(c.tree) as HistoryTree | null;
      const store = clone(c.store);
      if (c.error !== undefined) return errorMatches(() => foldTreeIntoStore(store, tree), c.error);
      expect(JSON.stringify(foldTreeIntoStore(store, tree))).toBe(JSON.stringify(c.result));
      expect(store).toEqual(c.store); // pure
    });
  test("round trip store -> tree -> store -> tree is stable", () => {
    const c = p[0]!;
    const tree = projectStoreToTree(c.store, c.chatKey, c.indexes);
    const store2 = foldTreeIntoStore(c.store, tree);
    expect(projectStoreToTree(store2, c.chatKey, c.indexes)).toEqual(tree);
  });
});

